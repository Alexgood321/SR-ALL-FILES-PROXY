"""Minimal HAPP target adapter; canonical conversion is owned by INCY."""
import argparse
import copy
from pathlib import Path

import generate_incy_xray_policy as incy

ROOT = Path(__file__).resolve().parents[1]


def validate_happ(policy):
    try:
        incy.validate_shape(policy)
    except RuntimeError as exc:
        raise ValueError(str(exc)) from exc
    if not any(r.get('inboundTag') == ['dns-internal'] and r.get('outboundTag') == 'proxy'
               for r in policy['routing']['rules']):
        raise ValueError('missing DNS proxy routing guard')


def convert_happ():
    policy, _, _ = incy.convert_xray()
    # HAPP uses the literal proxy/direct/block convention already emitted here.
    validate_happ(policy)
    return copy.deepcopy(policy)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'happ/xray-policy.json')
    parser.add_argument('--report', type=Path, default=ROOT / 'happ/xray-conversion-report.md')
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--write-validation-config', type=Path)
    args = parser.parse_args()
    policy = convert_happ()
    report = ('# HAPP canonical Xray policy\n\n'
              'Generated by the existing INCY canonical converter; dns/routing parity.\n'
              'HAPP proxy/direct/block tags match without node-name remapping.\n'
              'Canonical DNS semantics are unchanged; no extra global System fallback.\n'
              'Xray syntax validation is not HAPP iOS tunnel/E2E acceptance.\n')
    values = [(args.output, incy.render(policy)), (args.report, report)]
    if args.write_validation_config:
        args.write_validation_config.parent.mkdir(parents=True, exist_ok=True)
        args.write_validation_config.write_text(incy.render(incy.validation_config(policy)), encoding='utf-8')
    if args.check:
        return 0 if all(p.is_file() and p.read_text(encoding='utf-8') == text for p, text in values) else 1
    for path, text in values:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding='utf-8')
    return 0

if __name__ == '__main__':
    raise SystemExit(main())
